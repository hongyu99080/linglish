function parseWordFrequency(data) {
  const lines = data.split('\n');
  const wordMap = new Map();

  for (const line of lines) {
    const parts = line.trim().split(',');
    if (parts.length >= 2) {
      const word = parts[0].toLowerCase().trim();
      const rank = parseInt(parts[1], 10);
      if (word && !isNaN(rank) && !wordMap.has(word)) {
        wordMap.set(word, rank);
      }
    }
  }

  return wordMap;
}

async function importWordFrequency() {
  const pool = new Pool({
    connectionString: process.env.DATABASE_URL,
  });

  try {
    console.log('Starting comprehensive word frequency import...\n');

    // Parse the embedded frequency data
    const wordRanks = parseWordFrequency(WORD_FREQUENCY_DATA);
    console.log(`Loaded ${wordRanks.size} words from frequency list`);

    // Update words in database
    let updated = 0;
    let notFound = 0;
    const batchSize = 100;
    const entries = Array.from(wordRanks.entries());

    console.log('Updating word frequencies in database...');

    for (let i = 0; i < entries.length; i += batchSize) {
      const batch = entries.slice(i, i + batchSize);

      for (const [word, rank] of batch) {
        const result = await pool.query(
          `UPDATE words SET frequency_rank = $1, updated_at = NOW()
           WHERE word_lowercase = $2
           RETURNING id`,
          [rank, word]
        );

        if (result.rowCount > 0) {
          updated++;
        } else {
          notFound++;
        }
      }

      // Progress indicator
      if ((i + batchSize) % 500 === 0 || i + batchSize >= entries.length) {
        console.log(`  Processed ${Math.min(i + batchSize, entries.length)}/${entries.length} words...`);
      }
    }

    console.log(`\n✓ Updated ${updated} words with frequency ranks`);
    console.log(`  ${notFound} words from list not found in database`);

    // Assign default ranks to remaining words based on various criteria
    console.log('\nAssigning default ranks to remaining words...');

    // Strategy 1: Words with high lookup_count get ranks 3001-5000
    const popularResult = await pool.query(`
      UPDATE words w
      SET frequency_rank = sub.new_rank,
          updated_at = NOW()
      FROM (
        SELECT id, 3000 + ROW_NUMBER() OVER (ORDER BY lookup_count DESC, id) as new_rank
        FROM words
        WHERE (frequency_rank IS NULL OR frequency_rank = 0)
          AND lookup_count >= 10
        ORDER BY lookup_count DESC, id
        LIMIT 2000
      ) sub
      WHERE w.id = sub.id
      RETURNING w.id
    `);
    console.log(`  Assigned ranks 3001-5000 to ${popularResult.rowCount} popular words`);

    // Strategy 2: Words with medium lookup_count get ranks 5001-8000
    const mediumResult = await pool.query(`
      UPDATE words w
      SET frequency_rank = sub.new_rank,
          updated_at = NOW()
      FROM (
        SELECT id, 5000 + ROW_NUMBER() OVER (ORDER BY lookup_count DESC NULLS LAST, id) as new_rank
        FROM words
        WHERE (frequency_rank IS NULL OR frequency_rank = 0)
          AND (lookup_count < 10 OR lookup_count IS NULL)
          AND learned_by_count > 0
        ORDER BY lookup_count DESC NULLS LAST, id
        LIMIT 3000
      ) sub
      WHERE w.id = sub.id
      RETURNING w.id
    `);
    console.log(`  Assigned ranks 5001-8000 to ${mediumResult.rowCount} medium frequency words`);

    // Strategy 3: Remaining words get ranks 8001+
    const remainingResult = await pool.query(`
      UPDATE words w
      SET frequency_rank = sub.new_rank,
          updated_at = NOW()
      FROM (
        SELECT id, 8000 + ROW_NUMBER() OVER (ORDER BY id) as new_rank
        FROM words
        WHERE frequency_rank IS NULL OR frequency_rank = 0
      ) sub
      WHERE w.id = sub.id
      RETURNING w.id
    `);
    console.log(`  Assigned ranks 8001+ to ${remainingResult.rowCount} remaining words`);

    // Show summary
    const summaryResult = await pool.query(`
      SELECT
        COUNT(*) as total,
        COUNT(*) FILTER (WHERE frequency_rank > 0 AND frequency_rank <= 1000) as top_1000,
        COUNT(*) FILTER (WHERE frequency_rank > 1000 AND frequency_rank <= 3000) as rank_1001_3000,
        COUNT(*) FILTER (WHERE frequency_rank > 3000 AND frequency_rank <= 5000) as rank_3001_5000,
        COUNT(*) FILTER (WHERE frequency_rank > 5000 AND frequency_rank <= 8000) as rank_5001_8000,
        COUNT(*) FILTER (WHERE frequency_rank > 8000) as rank_8001_plus,
        COUNT(*) FILTER (WHERE frequency_rank IS NULL OR frequency_rank = 0) as no_rank
      FROM words
    `);

    const summary = summaryResult.rows[0];
    console.log('\n========================================');
    console.log('Word Frequency Distribution Summary');
    console.log('========================================');
    console.log(`  Top 1000 (高频核心词):     ${summary.top_1000}`);
    console.log(`  1001-3000 (高频常用词):    ${summary.rank_1001_3000}`);
    console.log(`  3001-5000 (中高频词):      ${summary.rank_3001_5000}`);
    console.log(`  5001-8000 (中频词):        ${summary.rank_5001_8000}`);
    console.log(`  8001+ (低频词):            ${summary.rank_8001_plus}`);
    console.log(`  No rank:                   ${summary.no_rank}`);
    console.log(`  Total words:               ${summary.total}`);
    console.log('========================================');

    // Show some examples
    const examples = await pool.query(`
      SELECT word, frequency_rank
      FROM words
      WHERE frequency_rank > 0
      ORDER BY frequency_rank
      LIMIT 20
    `);

    console.log('\nTop 20 highest frequency words in database:');
    examples.rows.forEach((row, i) => {
      console.log(`  ${i + 1}. ${row.word} (rank: ${row.frequency_rank})`);
    });

    console.log('\n✓ Word frequency import complete!');

  } catch (err) {
    console.error('Error importing word frequency:', err);
    throw err;
  } finally {
    await pool.end();
  }
}

